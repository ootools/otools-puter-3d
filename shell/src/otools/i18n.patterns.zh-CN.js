/**
 * 模式表：带插值的文案按形状认。
 * ------------------------------------------------------------------
 * 上游有大量文案是模板串拼出来的（`Open ${name}`、`${n} slides`），
 * 永远不可能成为词典的键，只能按形状认。
 *
 * 每条都是**锚定正则**（`^…$`，不带 `g`）。替换函数返回**空串**表示
 * 「这条不适用」，让文案保持英文并出现在缺口报告里——宁可半句英文，
 * 也别拼出「重置 Reset all」这种半成品。
 *
 * 第二参数 `t` 是翻译函数：捕获组若本身是界面文案（如 `2D` / 标签名），
 * 可用 `t(组)` 递归再翻一次；若是用户数据（文件路径、对象名）就原样保留。
 *
 * ⚠️ `i18n-report.mjs` **不统计模式表**，它只按词典算覆盖率。本文件的
 * 效果要在运行时看，不要用报告的百分比验收。
 */
export const patterns = [
  // ── 关于对话框 / 应用名 ──────────────────────────────────────────
  [/^About (.+)$/, (m) => `关于 ${m[1]}`],
  [/^Show information about (.+)$/, (m) => `显示关于 ${m[1]} 的信息`],

  // ── 2D 稳定化（跟踪面板）───────────────────────────────────────
  [/^Add selected tracks to 2D (.+) stabilization$/, (m, t) => `将所选跟踪添加为 2D ${t(m[1]) || m[1]}稳定化`],
  [/^Remove selected track from (.+) stabilization$/, (m, t) => `从 ${t(m[1]) || m[1]}稳定化中移除所选跟踪`],
  [/^Select tracks which are used for (.+) stabilization$/, (m, t) => `选择用于 ${t(m[1]) || m[1]}稳定化的跟踪`],

  // ── 通道 / 帧 / 节点的标签 ─────────────────────────────────────
  [/^Channel (.+)$/, (m) => `通道 ${m[1]}`],
  [/^Frame (\d+)$/, (m) => `帧 ${m[1]}`],
  [/^Key (.+)$/, (m) => `关键帧 ${m[1]}`],
  [/^Key for (.+)$/, (m, t) => `为 ${t(m[1]) || m[1]} 指定快捷键`],
  [/^Zoom (.+)$/, (m) => `缩放 ${m[1]}`],
  [/^(.+) Global$/, (m) => `${m[1]} 全局`],
  [/^(.+) for the selected channels$/, (m, t) => `对所选通道的 ${t(m[1]) || m[1]}`],
  [/^(\d+) frames$/, (m) => `${m[1]} 帧`],
  [/^(.+) fps$/, (m) => `${m[1]} fps`],
  [/^(.+) Hz$/, (m) => `${m[1]} Hz`],

  // ── 锁定通道（多行 tooltip：`Lock 名称\n说明`）──────────────────
  [/^Lock (.+) (.+)\nDisable editing this channel in the 3D viewport$/,
    (m, t) => `锁定 ${t(m[1]) || m[1]} ${m[2]}\n禁止在三维视口中编辑此通道`],
  [/^Lock (.+) (.+)$/, (m, t) => `锁定 ${t(m[1]) || m[1]} ${m[2]}`],
  [/^(.+)\nShift-click to extend, (\d+) to switch$/,
    (m, t) => `${t(m[1]) || m[1]}\n按住 Shift 单击可扩展选择，按 ${m[2]} 切换`],
  [/^(.+)\nLink a node to this input$/, (m, t) => `${t(m[1]) || m[1]}\n将节点链接到此输入`],
  [/^(.+)\n#(.+)$/, (m, t) => `${t(m[1]) || m[1]}\n#${m[2]}`],
];
